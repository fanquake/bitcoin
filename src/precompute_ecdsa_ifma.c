#include <inttypes.h>
#include <stdio.h>
#include <stdlib.h>

#include "../include/secp256k1.h"

#include "assumptions.h"
#include "util.h"

#include "field_impl.h"
#include "group_impl.h"
#include "int128_impl.h"

#define ECDSA_IFMA_Q_TABLE 8
#define ECDSA_IFMA_JOINT_TABLE 256

static uint64_t secp256k1_ecdsa_ifma_get_bits(const unsigned char *b32, unsigned int offset, unsigned int count) {
    uint64_t ret = 0;
    unsigned int i;
    for (i = 0; i < count; i++) {
        unsigned int bit = offset + i;
        ret |= (uint64_t)((b32[31 - (bit >> 3)] >> (bit & 7)) & 1U) << i;
    }
    return ret;
}

static void secp256k1_ecdsa_ifma_fe_to_limbs(uint64_t limbs[5], secp256k1_fe *fe) {
    unsigned char b32[32];
    int i;
    secp256k1_fe_normalize_var(fe);
    secp256k1_fe_get_b32(b32, fe);
    for (i = 0; i < 4; i++) {
        limbs[i] = secp256k1_ecdsa_ifma_get_bits(b32, 52U * (unsigned int)i, 52);
    }
    limbs[4] = secp256k1_ecdsa_ifma_get_bits(b32, 208, 48);
}

static void secp256k1_ecdsa_ifma_print_vector(FILE *fp, const char *name, const uint64_t limbs[5]) {
    int i;
    fprintf(fp, "const uint64_t %s[5] = {\n    ", name);
    for (i = 0; i < 5; i++) {
        fprintf(fp, "UINT64_C(0x%013" PRIx64 ")%s", limbs[i], i == 4 ? "\n" : ", ");
    }
    fprintf(fp, "};\n\n");
}

static void secp256k1_ecdsa_ifma_print_table(FILE *fp, const char *name, uint64_t table[5][ECDSA_IFMA_JOINT_TABLE]) {
    int limb;
    int entry;
    fprintf(fp, "const uint64_t %s[5][SECP256K1_ECDSA_IFMA_JOINT_TABLE] = {\n", name);
    for (limb = 0; limb < 5; limb++) {
        fprintf(fp, "    {\n");
        for (entry = 0; entry < ECDSA_IFMA_JOINT_TABLE; entry++) {
            const char *suffix;
            if ((entry & 3) == 0) {
                fprintf(fp, "        ");
            }
            suffix = entry == ECDSA_IFMA_JOINT_TABLE - 1 ? "\n" : ((entry & 3) == 3 ? ",\n" : ", ");
            fprintf(fp, "UINT64_C(0x%013" PRIx64 ")%s", table[limb][entry], suffix);
        }
        fprintf(fp, "    }%s\n", limb == 4 ? "" : ",");
    }
    fprintf(fp, "};\n\n");
}

int main(void) {
    const char outfile[] = "src/precomputed_ecdsa_ifma.c";
    secp256k1_ge fixed[ECDSA_IFMA_Q_TABLE];
    secp256k1_ge fixed_phi[ECDSA_IFMA_Q_TABLE];
    uint64_t gx[5], gy[5], gphix[5], gphiy[5];
    uint64_t joint_x[5][ECDSA_IFMA_JOINT_TABLE];
    uint64_t joint_y[5][ECDSA_IFMA_JOINT_TABLE];
    secp256k1_ge two;
    secp256k1_gej two_j;
    secp256k1_gej cur;
    FILE *fp;
    int i;
    int aenc;
    int benc;

    secp256k1_gej_set_ge(&cur, &secp256k1_ge_const_g);
    secp256k1_gej_double_var(&two_j, &cur, NULL);
    secp256k1_ge_set_gej_var(&two, &two_j);
    for (i = 0; i < ECDSA_IFMA_Q_TABLE; i++) {
        secp256k1_gej tmp = cur;
        secp256k1_ge_set_gej_var(&fixed[i], &tmp);
        secp256k1_ge_mul_lambda(&fixed_phi[i], &fixed[i]);
        if (i + 1 != ECDSA_IFMA_Q_TABLE) {
            secp256k1_gej_add_ge_var(&cur, &cur, &two, NULL);
        }
    }
    secp256k1_ecdsa_ifma_fe_to_limbs(gx, &fixed[0].x);
    secp256k1_ecdsa_ifma_fe_to_limbs(gy, &fixed[0].y);
    secp256k1_ecdsa_ifma_fe_to_limbs(gphix, &fixed_phi[0].x);
    secp256k1_ecdsa_ifma_fe_to_limbs(gphiy, &fixed_phi[0].y);
    for (aenc = 0; aenc < 16; aenc++) {
        secp256k1_ge a = fixed[aenc & 7];
        if (aenc >= 8) {
            secp256k1_ge_neg(&a, &a);
        }
        for (benc = 0; benc < 16; benc++) {
            secp256k1_ge b = fixed_phi[benc & 7];
            secp256k1_ge sum;
            secp256k1_gej sumj;
            uint64_t x[5];
            uint64_t y[5];
            int at = aenc * 16 + benc;
            int limb;
            if (benc >= 8) {
                secp256k1_ge_neg(&b, &b);
            }
            secp256k1_gej_set_ge(&sumj, &a);
            secp256k1_gej_add_ge_var(&sumj, &sumj, &b, NULL);
            CHECK(!secp256k1_gej_is_infinity(&sumj));
            secp256k1_ge_set_gej_var(&sum, &sumj);
            secp256k1_ecdsa_ifma_fe_to_limbs(x, &sum.x);
            secp256k1_ecdsa_ifma_fe_to_limbs(y, &sum.y);
            for (limb = 0; limb < 5; limb++) {
                joint_x[limb][at] = x[limb];
                joint_y[limb][at] = y[limb];
            }
        }
    }

    fp = fopen(outfile, "w");
    if (fp == NULL) {
        fprintf(stderr, "Could not open %s for writing!\n", outfile);
        return EXIT_FAILURE;
    }
    fprintf(fp, "/* This file was automatically generated by precompute_ecdsa_ifma. */\n");
    fprintf(fp, "#include \"util.h\"\n");
    fprintf(fp, "#include \"ecdsa_ifma_config.h\"\n");
    fprintf(fp, "#ifdef SECP256K1_ECDSA_VERIFY_MANY_IFMA\n");
    fprintf(fp, "#include \"precomputed_ecdsa_ifma.h\"\n\n");
    secp256k1_ecdsa_ifma_print_vector(fp, "secp256k1_ecdsa_ifma_gx", gx);
    secp256k1_ecdsa_ifma_print_vector(fp, "secp256k1_ecdsa_ifma_gy", gy);
    secp256k1_ecdsa_ifma_print_vector(fp, "secp256k1_ecdsa_ifma_gphix", gphix);
    secp256k1_ecdsa_ifma_print_vector(fp, "secp256k1_ecdsa_ifma_gphiy", gphiy);
    secp256k1_ecdsa_ifma_print_table(fp, "secp256k1_ecdsa_ifma_joint_x", joint_x);
    secp256k1_ecdsa_ifma_print_table(fp, "secp256k1_ecdsa_ifma_joint_y", joint_y);
    fprintf(fp, "#endif /* SECP256K1_ECDSA_VERIFY_MANY_IFMA */\n");
    fclose(fp);
    return EXIT_SUCCESS;
}
